import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import { formatPHTDateTime } from './formatters';

interface ExportColumn {
  header: string;
  dataKey: string;
}

/**
 * Export data array to a styled, professional PDF document
 */
export function exportReportToPDF(
  title: string,
  columns: ExportColumn[],
  rows: Record<string, any>[],
  metadata?: { dateRange?: string; generatedBy?: string }
) {
  const doc = new jsPDF({
    orientation: columns.length > 6 ? 'landscape' : 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Title Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 60, 'F');

  // Accent Line
  doc.setFillColor(245, 158, 11); // amber-500
  doc.rect(0, 58, pageWidth, 3, 'F');

  // Header text
  doc.setFontSize(15);
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.text('SOLAR PANEL POWER PLANT - KIRAHON, MISAMIS ORIENTAL', 30, 26);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text(title, 30, 44);

  // Sub-header metadata
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500
  const genTime = `Generated: ${formatPHTDateTime(new Date().toISOString())}`;
  const generatedBy = metadata?.generatedBy ? `Generated by: ${metadata.generatedBy}` : 'System Export';
  const range = metadata?.dateRange ? `Period: ${metadata.dateRange}` : 'Period: All recorded dates';

  doc.text(`${genTime}  |  ${generatedBy}  |  ${range}`, 30, 80);

  // Table content
  const tableData = rows.map((row) =>
    columns.map((col) => {
      const val = row[col.dataKey];
      return val === null || val === undefined ? '—' : String(val);
    })
  );

  autoTable(doc, {
    startY: 92,
    head: [columns.map((col) => col.header)],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59], // slate-800
      textColor: [241, 245, 249],
      fontSize: 9,
      fontStyle: 'bold',
      cellPadding: 6,
    },
    bodyStyles: {
      textColor: [30, 41, 59],
      fontSize: 8,
      cellPadding: 5,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252], // slate-50
    },
    margin: { top: 92, left: 30, right: 30, bottom: 40 },
    didDrawPage: (data) => {
      // Footer page numbering
      const str = `Page ${data.pageNumber}`;
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(str, pageWidth - 60, doc.internal.pageSize.getHeight() - 15);
      doc.text('Solar Panel Power Plant Maintenance Management System · Kirahon, Misamis Oriental', 30, doc.internal.pageSize.getHeight() - 15);
    },
  });

  const sanitized = title.toLowerCase().replace(/[^a-z0-9]/g, '_');
  doc.save(`${sanitized}_${Date.now()}.pdf`);
}

/**
 * Export data array to Microsoft Excel (.xlsx)
 */
export function exportReportToExcel(
  title: string,
  columns: ExportColumn[],
  rows: Record<string, any>[]
) {
  const formattedRows = rows.map((row) => {
    const formattedObj: Record<string, any> = {};
    columns.forEach((col) => {
      formattedObj[col.header] = row[col.dataKey] ?? '—';
    });
    return formattedObj;
  });

  const worksheet = XLSX.utils.json_to_sheet(formattedRows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Report');

  const sanitized = title.toLowerCase().replace(/[^a-z0-9]/g, '_');
  XLSX.writeFile(workbook, `${sanitized}_${Date.now()}.xlsx`);
}
